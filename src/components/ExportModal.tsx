import React, { useState } from 'react';
import { X, Copy, Check, Download, FileText, Code2 } from 'lucide-react';
import type { IncidentRecord } from '../types';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  incident: IncidentRecord;
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  incident,
}) => {
  const [format, setFormat] = useState<'markdown' | 'json'>('markdown');
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const generateMarkdown = (): string => {
    return `# Incident Post-Mortem Report: ${incident.title}

**Incident ID:** \`${incident.id}\`  
**Severity:** ${incident.severity}  
**Status:** ${incident.status}  
**Service:** \`${incident.service}\`  
**Environment:** \`${incident.environment}\`  
**Created:** ${new Date(incident.createdAt).toUTCString()}  
**Last Updated:** ${new Date(incident.updatedAt).toUTCString()}  

---

## 1. Executive Summary
${incident.summary}

## 2. Blast Radius & Customer Impact
- **Impact Assessment:** ${incident.blastRadius}
- **Error Rate:** ${incident.metrics.errorRate || 'N/A'}
- **Latency Impact (p99):** ${incident.metrics.p99Latency || 'N/A'}
- **Affected Nodes/Replicas:** ${incident.metrics.affectedReplicas || 'N/A'}

## 3. Root Cause Analysis
${incident.rootCauses
  .map(
    (rc, i) => `### Hypothesis ${i + 1} (${rc.confidence}% Confidence)
- **Failure Mechanism:** ${rc.hypothesis}
- **Log Evidence:**
${(rc.evidence || []).map(e => `  - \`${e}\``).join('\n')}
- **Contributing Factors:**
${(rc.contributingFactors || []).map(cf => `  - ${cf}`).join('\n')}
`
  )
  .join('\n')}

## 4. Remediation & Action Items
| Task | Category | Status |
|---|---|---|
${incident.actionItems
  .map(
    a =>
      `| ${a.description} | \`${a.type}\` | ${
        a.status === 'completed' ? '✅ Completed' : '⏳ Pending'
      } |`
  )
  .join('\n')}

## 5. Diagnostic Commands
${incident.diagnosticCommands
  .map(
    c => `### ${c.label} (${c.category})
\`\`\`bash
${c.command}
\`\`\`
*Explanation:* ${c.explanation}
`
  )
  .join('\n')}

---
*Generated by IncidentLens on Cloudflare Workers AI & Durable Objects runtime.*
`;
  };

  const content =
    format === 'markdown'
      ? generateMarkdown()
      : JSON.stringify(incident, null, 2);

  const handleCopy = () => {
    navigator.clipboard.writeText(content);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const filename = `incident-${incident.id}.${format === 'markdown' ? 'md' : 'json'}`;
    const blob = new Blob([content], {
      type: format === 'markdown' ? 'text/markdown' : 'application/json',
    });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/75 backdrop-blur-sm animate-in fade-in duration-150">
      <div className="relative w-full max-w-3xl bg-[#0E131F] border border-gray-800 rounded-xl shadow-2xl flex flex-col max-h-[90vh] overflow-hidden">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-gray-800 bg-[#111827]/70">
          <div className="flex items-center space-x-2">
            <FileText className="w-4 h-4 text-purple-400" />
            <h3 className="text-sm font-semibold text-gray-100">
              Export Post-Mortem Report
            </h3>
          </div>
          <button
            onClick={onClose}
            className="p-1 rounded text-gray-400 hover:text-white hover:bg-gray-800"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Toolbar */}
        <div className="flex items-center justify-between px-6 py-3 border-b border-gray-800/80 bg-[#0B0F19]">
          <div className="flex items-center space-x-1 text-xs">
            <button
              onClick={() => setFormat('markdown')}
              className={`px-3 py-1 rounded-md font-mono transition-colors ${
                format === 'markdown'
                  ? 'bg-blue-600 text-white font-semibold'
                  : 'bg-gray-800 text-gray-400 hover:text-white'
              }`}
            >
              Markdown (.md)
            </button>
            <button
              onClick={() => setFormat('json')}
              className={`px-3 py-1 rounded-md font-mono transition-colors ${
                format === 'json'
                  ? 'bg-blue-600 text-white font-semibold'
                  : 'bg-gray-800 text-gray-400 hover:text-white'
              }`}
            >
              JSON (.json)
            </button>
          </div>

          <div className="flex items-center space-x-2">
            <button
              onClick={handleCopy}
              className="flex items-center space-x-1.5 px-3 py-1.5 rounded-md bg-gray-800 hover:bg-gray-700 text-gray-200 text-xs font-medium transition-colors"
            >
              {copied ? (
                <>
                  <Check className="w-3.5 h-3.5 text-emerald-400" />
                  <span className="text-emerald-400">Copied!</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5" />
                  <span>Copy Content</span>
                </>
              )}
            </button>

            <button
              onClick={handleDownload}
              className="flex items-center space-x-1.5 px-3 py-1.5 rounded-md bg-blue-600 hover:bg-blue-500 text-white text-xs font-medium transition-colors"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download File</span>
            </button>
          </div>
        </div>

        {/* Preview Area */}
        <div className="flex-1 overflow-y-auto p-6 bg-[#070A11]">
          <pre className="font-mono text-xs text-gray-300 whitespace-pre-wrap leading-relaxed select-all">
            {content}
          </pre>
        </div>
      </div>
    </div>
  );
};
