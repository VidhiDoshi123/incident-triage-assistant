import React, { useState } from 'react';
import { X, Copy, Check, Download, FileText, Code2 } from 'lucide-react';
import type { IncidentRecord } from '../types';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  incident: IncidentRecord;
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  incident,
}) => {
  const [format, setFormat] = useState<'markdown' | 'json'>('markdown');
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const generateMarkdown = (): string => {
    return `# Incident Post-Mortem Report: ${incident.title}

**Incident ID:** \`${incident.id}\`  
**Severity:** \`${incident.severity}\`  
**Status:** \`${incident.status}\`  
**Affected Service:** \`${incident.service}\`  
**Environment:** \`${incident.environment}\`  
**Report Created:** ${new Date(incident.createdAt).toUTCString()}  
**Last State Transition:** ${new Date(incident.updatedAt).toUTCString()}  

---

## 1. Executive Summary
${incident.summary}

---

## 2. Stage 1: Error Understanding & Extraction
- **Core Failure Mechanism:** ${incident.errorUnderstanding?.failureMechanism || 'Unhandled operational exception'}
- **Affected Subsystem / Component:** \`${incident.errorUnderstanding?.affectedComponent || incident.service}\`
- **Extracted Error Signatures / Codes:**
${(incident.errorUnderstanding?.extractedErrorCodes || ['N/A']).map(c => `  - \`${c}\``).join('\n')}

### Chronological Failure Sequence
${(incident.errorUnderstanding?.timeline || ['Failure initiated and detected by monitoring']).map((step, idx) => `${idx + 1}. ${step}`).join('\n')}

---

## 3. Stage 2: Severity Categorization & Blast Radius
- **Severity Level:** \`${incident.severity}\`
- **Severity Justification:** ${incident.severityAssessment?.justification || incident.blastRadius}
- **Observed Blast Radius:** ${incident.blastRadius}
- **Impacted Scope / Audiences:** ${(incident.severityAssessment?.impactedAudiences || ['API traffic']).join(', ')}

### Telemetry & Impact Metrics
- **Spike Error Rate:** ${incident.metrics.errorRate || 'Elevated'}
- **Latency Impact (p99):** ${incident.metrics.p99Latency || 'Degraded'}
- **Affected Pods / Replicas:** ${incident.metrics.affectedReplicas || 'Multiple'}

---

## 4. Stage 3: Root Cause Analysis (RCA) & Confidence
${
  incident.confidenceAssessment?.isConfident === false
    ? `> [!WARNING]
> **Inconclusive Diagnosis (Confidence: ${incident.confidenceAssessment.primaryConfidence}%)**  
> ${incident.confidenceAssessment.ambiguityExplanation}
> 
> **Missing Telemetry to Confirm Root Cause:**
${(incident.confidenceAssessment.missingTelemetry || []).map(m => `> - ${m}`).join('\n')}
`
    : ''
}
${incident.rootCauses
  .map(
    (rc, i) => `### Hypothesis ${i + 1} (${rc.confidence}% Confidence Rating)
- **Failure Hypothesis:** ${rc.hypothesis}
- **Direct Log Evidence:**
${(rc.evidence || []).map(e => `  - \`${e}\``).join('\n')}
- **Contributing Factors:**
${(rc.contributingFactors || []).map(cf => `  - ${cf}`).join('\n')}
`
  )
  .join('\n')}

---

## 5. Stage 4: Prioritized Troubleshooting Plan
| Priority | Task Description | Category | Status |
|---|---|---|---|
${incident.actionItems
  .map(
    a =>
      `| \`${(a.priority || 'P1').toUpperCase()}\` | ${a.description} | \`${a.type}\` | ${
        a.status === 'completed' ? '✅ Completed' : '⏳ Pending'
      } |`
  )
  .join('\n')}

### Mitigation Runbook Commands
${incident.actionItems
  .filter(a => a.command)
  .map(
    a => `**${a.description} (${(a.priority || 'P1').toUpperCase()}):**
\`\`\`bash
${a.command}
\`\`\`
*Context: ${a.explanation || ''}*
`
  )
  .join('\n')}

---

## 6. Diagnostic CLI Commands
${incident.diagnosticCommands
  .map(
    c => `### ${c.label} (\`${c.category}\`)
\`\`\`bash
${c.command}
\`\`\`
*Target Observation: ${c.explanation}*
`
  )
  .join('\n')}

---

## 7. Cross-Incident Knowledge Correlation
${
  incident.crossIncidentReferences && incident.crossIncidentReferences.length > 0
    ? incident.crossIncidentReferences
        .map(
          r => `- **Related Incident:** \`${r.relatedIncidentTitle}\` (\`${r.relatedIncidentId}\`)
  - **Similarity Factor:** ${r.similarityFactor}
  - **Analysis:** ${r.comparisonNote}`
        )
        .join('\n')
    : 'No directly correlated past incidents detected in SQLite index.'
}

---
*Report auto-generated by IncidentLens • Powered by Cloudflare Workers AI & Durable Objects SQLite Runtime.*
`;
  };

  const content =
    format === 'markdown'
      ? generateMarkdown()
      : JSON.stringify(incident, null, 2);

  const handleCopy = () => {
    navigator.clipboard.writeText(content);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const filename = `incident-${incident.id}.${format === 'markdown' ? 'md' : 'json'}`;
    const blob = new Blob([content], {
      type: format === 'markdown' ? 'text/markdown' : 'application/json',
    });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/75 backdrop-blur-sm animate-in fade-in duration-150">
      <div className="relative w-full max-w-3xl bg-[#0E131F] border border-gray-800 rounded-xl shadow-2xl flex flex-col max-h-[90vh] overflow-hidden">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-gray-800 bg-[#111827]/70">
          <div className="flex items-center space-x-2">
            <FileText className="w-4 h-4 text-purple-400" />
            <h3 className="text-sm font-semibold text-gray-100">
              Export Post-Mortem Report
            </h3>
          </div>
          <button
            onClick={onClose}
            className="p-1 rounded text-gray-400 hover:text-white hover:bg-gray-800"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Toolbar */}
        <div className="flex items-center justify-between px-6 py-3 border-b border-gray-800/80 bg-[#0B0F19]">
          <div className="flex items-center space-x-1 text-xs">
            <button
              onClick={() => setFormat('markdown')}
              className={`px-3 py-1 rounded-md font-mono transition-colors ${
                format === 'markdown'
                  ? 'bg-blue-600 text-white font-semibold'
                  : 'bg-gray-800 text-gray-400 hover:text-white'
              }`}
            >
              Markdown (.md)
            </button>
            <button
              onClick={() => setFormat('json')}
              className={`px-3 py-1 rounded-md font-mono transition-colors ${
                format === 'json'
                  ? 'bg-blue-600 text-white font-semibold'
                  : 'bg-gray-800 text-gray-400 hover:text-white'
              }`}
            >
              JSON (.json)
            </button>
          </div>

          <div className="flex items-center space-x-2">
            <button
              onClick={handleCopy}
              className="flex items-center space-x-1.5 px-3 py-1.5 rounded-md bg-gray-800 hover:bg-gray-700 text-gray-200 text-xs font-medium transition-colors"
            >
              {copied ? (
                <>
                  <Check className="w-3.5 h-3.5 text-emerald-400" />
                  <span className="text-emerald-400">Copied!</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5" />
                  <span>Copy Content</span>
                </>
              )}
            </button>

            <button
              onClick={handleDownload}
              className="flex items-center space-x-1.5 px-3 py-1.5 rounded-md bg-blue-600 hover:bg-blue-500 text-white text-xs font-medium transition-colors"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download File</span>
            </button>
          </div>
        </div>

        {/* Preview Area */}
        <div className="flex-1 overflow-y-auto p-6 bg-[#070A11]">
          <pre className="font-mono text-xs text-gray-300 whitespace-pre-wrap leading-relaxed select-all">
            {content}
          </pre>
        </div>
      </div>
    </div>
  );
};
